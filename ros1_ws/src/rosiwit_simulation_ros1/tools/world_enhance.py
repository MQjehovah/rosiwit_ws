INCLUDE_RE = re.compile(r'[ \t]*<include>.*?</include>\n', re.S)


def _strip_includes(src, uris):
    """把指定 model:// 的 include 整块摘掉，返回 (新文本, 摘掉的数量)。"""
    count = [0]

    def repl(m):
        blk = m.group(0)
        if any(u in blk for u in uris):
            count[0] += 1
            return ''
        return blk

    return INCLUDE_RE.sub(repl, src), count[0]


